#include "libft.h"

char	*ft_strrchr(const char *s, int c)
{
	const char		*last;
	unsigned char	ch;

	last = NULL;
	ch = (unsigned char)c;
	while (*s != '\0')
	{
		if ((unsigned char)*s == ch)
			last = s;
		s++;
	}
	if (ch == '\0')
		return ((char *)s);
	return ((char *)last);
}
